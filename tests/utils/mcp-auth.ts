/**
 * Register OAuth client with MCP server
 */
export async function registerOAuthClient(baseUrl: string): Promise<OAuthClientData> {
  console.log("[OAuth] Step 1: Registering client...");
  const response = await fetch(`${baseUrl}/api/auth/oauth2/register`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Origin: getTestRequestOrigin() },
    body: JSON.stringify({
      client_name: "test-mcp-client-" + Date.now(),
      redirect_uris: [OAUTH_REDIRECT_URI],
      grant_types: ["authorization_code", "refresh_token"],
      token_endpoint_auth_method: "client_secret_post",
    }),
  });

  if (!response.ok) {
    const error = await response.text();
    console.error("[OAuth] Registration failed:", response.status, error);
    throw new Error(`OAuth client registration failed: ${response.status}`);
  }

  const data = (await response.json()) as OAuthClientData;
  console.log("[OAuth] ✓ Client registered:", data.client_id);
  return data;
}

/**
 * Sign in user and get session cookie
 * @param baseUrl - Base URL of the application
 * @param email - User email
 * @param password - User password
 * @returns Session cookie value
 */
export async function signInUser(
  baseUrl: string,
  email: string,
  password: string,
): Promise<string> {
  console.log("[OAuth] Step 2: Signing in:", email);
  const response = await fetch(`${baseUrl}/api/auth/sign-in/email`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Origin: getTestRequestOrigin() },
    body: JSON.stringify({
      email,
      password,
      rememberMe: true,
    }),
  });

  if (!response.ok) {
    const error = await response.text();
    console.error("[OAuth] Sign in failed:", response.status, error);
    throw new Error(`Sign in failed: ${response.status}`);
  }

  // Extract session cookie from Set-Cookie header
  const setCookieHeader = response.headers.get("set-cookie");
  console.log("[OAuth] Set-Cookie:", setCookieHeader ? "present" : "MISSING");

  const sessionCookie = extractSessionCookie(setCookieHeader);

  if (!sessionCookie) {
    console.error("[OAuth] Session cookie not found in header");
    throw new Error("No session cookie in sign-in response");
  }

  console.log("[OAuth] ✓ Session cookie extracted");
  return sessionCookie;
}

/**
 * Verify user email via admin API
 * Requires admin session to call the admin endpoint
 */
async function verifyUserEmailViaAdmin(
  baseUrl: string,
  userEmail: string,
  adminSessionCookie: string,
): Promise<void> {
  console.log("[OAuth] Verifying email for:", userEmail);

  // Get all users to find the user ID (use search param for paginated results)
  const usersResponse = await fetch(
    `${baseUrl}/api/admin/users?search=${encodeURIComponent(userEmail)}&limit=10`,
    {
      headers: {
        Cookie: formatSessionCookie(baseUrl, adminSessionCookie),
      },
    },
  );

  if (!usersResponse.ok) {
    throw new Error(`Failed to get users list: ${usersResponse.status}`);
  }

  const usersData = (await usersResponse.json()) as {
    data: { users: Array<{ id: string; email: string }> };
  };
  const user = usersData.data?.users?.find((u) => u.email === userEmail);

  if (!user) {
    throw new Error(`User not found: ${userEmail}`);
  }

  // Call verify-email endpoint
  const verifyResponse = await fetch(`${baseUrl}/api/admin/users/${user.id}/verify-email`, {
    method: "POST",
    headers: {
      Cookie: formatSessionCookie(baseUrl, adminSessionCookie),
    },
  });

  if (!verifyResponse.ok) {
    const error = await verifyResponse.text();
    throw new Error(`Failed to verify email: ${verifyResponse.status} ${error}`);
  }

  console.log("[OAuth] ✓ Email verified for:", userEmail);
}

/**
 * Get authorization code via OAuth authorize endpoint
 */
export async function getAuthorizationCode(
  baseUrl: string,
  clientId: string,
  sessionCookie: string,
) {
  const verifier = randomBytes(32).toString("base64url");
  const challenge = createHash("sha256").update(verifier).digest("base64url");
  const state = randomBytes(24).toString("base64url");
  const authorizeUrl = new URL(baseUrl + "/api/auth/oauth2/authorize");
  authorizeUrl.search = new URLSearchParams({
    client_id: clientId,
    redirect_uri: OAUTH_REDIRECT_URI,
    response_type: "code",
    state,
    scope: "openid email profile offline_access",
    code_challenge: challenge,
    code_challenge_method: "S256",
  }).toString();
  const cookie = formatSessionCookie(baseUrl, sessionCookie);
  const response = await fetch(authorizeUrl, { headers: { Cookie: cookie }, redirect: "manual" });
  const location = response.headers.get("location");
  if (!location) throw new Error("Authorization did not redirect: " + response.status);
  let next = new URL(location, baseUrl);
  if (next.pathname.endsWith("/oauth/consent")) {
    const consent = await fetch(baseUrl + "/api/auth/oauth2/consent", {
      method: "POST",
      headers: {
        Cookie: cookie,
        Origin: getTestRequestOrigin(),
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ accept: true, oauth_query: next.searchParams.toString() }),
    });
    if (!consent.ok) throw new Error("Consent failed: " + consent.status);
    const body = (await consent.json()) as { url: string };
    next = new URL(body.url, baseUrl);
  }
  const code = next.searchParams.get("code");
  if (
    next.origin + next.pathname !== OAUTH_REDIRECT_URI ||
    next.searchParams.get("state") !== state ||
    !code
  ) {
    throw new Error("Expected the registered OAuth callback with the requested state and a code");
  }
  return { code, verifier };
}

export async function exchangeCodeForToken(
  baseUrl: string,
  authorization: { code: string; verifier: string },
  client: OAuthClientData,
) {
  const response = await fetch(baseUrl + "/api/auth/oauth2/token", {
    method: "POST",
    headers: { Origin: getTestRequestOrigin() },
    body: new URLSearchParams({
      grant_type: "authorization_code",
      code: authorization.code,
      code_verifier: authorization.verifier,
      redirect_uri: OAUTH_REDIRECT_URI,
      client_id: client.client_id,
      client_secret: client.client_secret,
    }),
  });
  if (!response.ok) throw new Error("OAuth exchange failed: " + response.status);
  return (await response.json()) as { access_token: string; refresh_token: string };
}

/**
 * Create authenticated MCP client via pure HTTP OAuth flow
 *
 * @param credentials - User credentials (defaults to admin)
 * @returns Authenticated MCP client with cleanup function
 *
 * @example
 * const { client, cleanup } = await createAuthenticatedMCPClient();
 * try {
 *   const result = await client.callTool({ name: 'workflow', arguments: { action: 'list' } });
 *   // ... test assertions
 * } finally {
 *   await cleanup();
 * }
 *
 * @example
 * // Custom user
 * const { client } = await createAuthenticatedMCPClient({
 *   email: 'user@example.com',
 *   password: 'userpass'
 * });
 *
 * @example
 * // With email verification (for non-admin users)
 * const { client } = await createAuthenticatedMCPClient({
 *   email: 'newuser@example.com',
 *   password: 'userpass',
 *   verifyEmail: true
 * });
 */
export async function createAuthenticatedMCPClient(
  credentials: {
    email: string;
    password: string;
    verifyEmail?: boolean;
    adminCredentials?: { email: string; password: string };
  } = DEFAULT_ADMIN_CREDENTIALS,
): Promise<MCPTestClient> {
  const baseUrl = getTestBaseUrl();
  const fetchUrl = getTestFetchUrl();

  console.log("[mcp-auth] Starting OAuth flow...");
  console.log(`[mcp-auth] baseUrl=${baseUrl}, fetchUrl=${fetchUrl}`);

  // If email verification is requested, do it first via admin API
  if (credentials.verifyEmail && credentials.email !== DEFAULT_ADMIN_CREDENTIALS.email) {
    const adminCreds = credentials.adminCredentials || DEFAULT_ADMIN_CREDENTIALS;
    console.log("[mcp-auth] Email verification requested, signing in as admin first...");
    const adminSessionCookie = await signInUser(fetchUrl, adminCreds.email, adminCreds.password);
    await verifyUserEmailViaAdmin(fetchUrl, credentials.email, adminSessionCookie);
    console.log("[mcp-auth] ✓ Email verified for user");
  }

  const registration = await registerOAuthClient(fetchUrl);
  const ownerSessionCookie = await signInUser(fetchUrl, credentials.email, credentials.password);
  const authorization = await getAuthorizationCode(
    fetchUrl,
    registration.client_id,
    ownerSessionCookie,
  );
  const { access_token: accessToken } = await exchangeCodeForToken(
    fetchUrl,
    authorization,
    registration,
  );

  // Step 5: Connect MCP client with retry — SQLite WAL may delay session visibility
  const maxConnectRetries = 5;
  for (let attempt = 1; attempt <= maxConnectRetries; attempt++) {
    try {
      const mcpClient = new Client({ name: "test-client", version: "1.0.0" }, { capabilities: {} });
      const mcpTransport = new StreamableHTTPClientTransport(new URL(`${fetchUrl}/mcp`), {
        requestInit: {
          headers: {
            Authorization: `Bearer ${accessToken}`,
          },
        },
      });

      console.log(
        `[OAuth] Step 5: Connecting MCP client (attempt ${attempt}/${maxConnectRetries})...`,
      );
      await mcpClient.connect(mcpTransport);
      console.log("[OAuth] ✓ MCP client connected");

      ownerSessions.set(mcpClient, ownerSessionCookie);

      return {
        client: mcpClient,
        transport: mcpTransport,
        accessToken,
        cleanup: async () => {
          await mcpClient.close();
        },
      };
    } catch (err) {
      const errMsg = String(err);
      console.error(`[OAuth] MCP connect error (attempt ${attempt}): ${errMsg.substring(0, 200)}`);
      if (
        attempt < maxConnectRetries &&
        (errMsg.includes("401") || errMsg.includes("invalid_token"))
      ) {
        const delay = attempt * 300;
        console.warn(
          `[OAuth] MCP connect got 401 (session not yet visible), retrying in ${delay}ms...`,
        );
        await new Promise((r) => setTimeout(r, delay));
        continue;
      }
      throw err;
    }
  }
  throw new Error("Unreachable: MCP connect retries exhausted");
}

/**
 * Read the first MCP text block as JSON, falling back to its raw text.
 * Use client.callTool directly when asserting isError or native content blocks.
 *
 * @param client - Authenticated MCP client
 * @param toolName - Name of the tool to call
 * @param args - Tool arguments
 * @returns Parsed first text block, or its text when it is not JSON
 *
 * @example
 * const result = await callMCPTool(client, 'workflow', { action: 'list' });
 * expect(result.workflows).toBeDefined();
 *
 * @example
 * const settings = await callMCPTool(client, 'settings', { action: 'get', category: 'ui' });
 * expect(settings).toBeDefined();
 */
export async function callMCPTool<T = any>(
  client: Client,
  toolName: string,
  args: Record<string, any> = {},
): Promise<T> {
  const result = await client.callTool({
    name: toolName,
    arguments: args,
  });

  if (!result.content || (result.content as any[]).length === 0) {
    throw new Error(`Tool ${toolName} returned no content`);
  }

  const content = (result.content as any[])[0];
  if (!("text" in content)) {
    throw new Error(`Tool ${toolName} returned non-text content`);
  }

  // Try to parse as JSON, if fails return raw text
  try {
    return JSON.parse(content.text) as T;
  } catch (e) {
    // Not JSON - return raw text
    return content.text as T;
  }
}

/**
 * Call MCP tool and return raw text response (for format verification)
 */
export async function callMCPToolRaw(
  client: Client,
  toolName: string,
  args: Record<string, any> = {},
): Promise<string> {
  const result = await client.callTool({
    name: toolName,
    arguments: args,
  });

  if (!result.content || (result.content as any[]).length === 0) {
    throw new Error(`Tool ${toolName} returned no content`);
  }

  const content = (result.content as any[])[0];
  if (!("text" in content)) {
    throw new Error(`Tool ${toolName} returned non-text content`);
  }

  return content.text;
}

/**
 * Prepare and execute one workflow start through the public replay-safe MCP contract.
 * Returns the raw execute response containing the reserved Process ID and first Step attempt.
 */
export async function startWorkflowExecution(
  client: Client,
  workflowId: string,
  options: {
    parentExecutionId?: string;
    note?: string;
    skipNotificationCheck?: boolean;
    skipTelegramCheck?: boolean;
  } = {},
): Promise<string> {
  const prepared = await callMCPToolRaw(client, "execution", {
    action: "prepare",
    workflowId,
    parentExecutionId: options.parentExecutionId ?? "none",
    ...(options.note ? { note: options.note } : {}),
    ...(options.skipNotificationCheck ? { skipNotificationCheck: true } : {}),
    ...(options.skipTelegramCheck ? { skipTelegramCheck: true } : {}),
  });
  const startAttemptId = prepared.match(/Start attempt ID:\s*([a-f0-9-]+)/i)?.[1];
  if (!startAttemptId) {
    throw new Error(`Start attempt ID missing from response: ${prepared}`);
  }
  return callMCPToolRaw(client, "execution", {
    action: "execute",
    startAttemptId,
  });
}

export interface RunningWorkflowExecution {
  processId: string;
  attemptId: string;
  response: string;
}

export function requireMCPResponseId(
  response: string,
  label: "Process" | "Start attempt" | "Step attempt",
): string {
  const id = response.match(new RegExp(`${label} ID:\\s*([a-f0-9-]+)`, "i"))?.[1];
  if (!id) throw new Error(`${label} ID missing from MCP response: ${response}`);
  return id;
}

export async function startWorkflowExecutionState(
  client: Client,
  workflowId: string,
  options: Parameters<typeof startWorkflowExecution>[2] = {},
): Promise<RunningWorkflowExecution> {
  const response = await startWorkflowExecution(client, workflowId, options);
  return {
    processId: requireMCPResponseId(response, "Process"),
    attemptId: requireMCPResponseId(response, "Step attempt"),
    response,
  };
}

export async function advanceWorkflowExecution(
  client: Client,
  execution: RunningWorkflowExecution,
  input: unknown,
): Promise<string> {
  const response = await callMCPToolRaw(client, "execution", {
    action: "step",
    processId: execution.processId,
    attemptId: execution.attemptId,
    input,
  });
  const nextAttemptId = response.match(/Step attempt ID:\s*([a-f0-9-]+)/i)?.[1];
  if (nextAttemptId) execution.attemptId = nextAttemptId;
  execution.response = response;
  return response;
}

/**
 * Parse token tool response (formatted text)
 * Extracts token, expires, and URL from formatted string
 */
export function parseTokenResponse(text: string): {
  token: string;
  expiresAt: string;
  uploadUrl?: string;
  downloadUrl?: string;
} {
  const lines = text.split("\n");
  const result: any = {};

  for (const line of lines) {
    const [key, ...valueParts] = line.split(":");
    const value = valueParts.join(":").trim();

    if (key.includes("Token")) {
      result.token = value;
    } else if (key.includes("Expires")) {
      result.expiresAt = value;
    } else if (key.includes("Upload URL")) {
      result.uploadUrl = value;
    } else if (key.includes("Download URL")) {
      result.downloadUrl = value;
    }
  }

  return result;
}
